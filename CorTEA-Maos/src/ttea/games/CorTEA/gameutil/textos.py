def t(chave: str) -> str:
    """Retorna o texto da ``chave`` no idioma atual (padrão: pt_BR)."""
    idioma = TEXTOS.get(GameSettings.CURRENT_LANG, TEXTOS["pt_BR"])
    return idioma.get(chave) or TEXTOS["pt_BR"].get(chave, chave)


def formatar_tempo(segundos: float) -> str:
    """Formata segundos como ``m:ss``."""
    segundos = max(0, int(round(segundos)))
    return f"{segundos // 60}:{segundos % 60:02d}"
